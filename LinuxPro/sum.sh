#!/usr/bin/env bash

# Включаем режим nounset.
# Если в скрипте случайно обратиться к переменной, которая не была задана,
# bash завершит выполнение с ошибкой. Это помогает быстрее находить опечатки.
set -o nounset

# Включаем pipefail.
# Если в pipeline вида `cmd1 | cmd2 | cmd3` одна из команд завершится с ошибкой,
# весь pipeline тоже будет считаться ошибочным.
set -o pipefail

# "$#" - количество аргументов, переданных скрипту.
# Для задачи нужны ровно два аргумента: первое число и второе число.
# Пример корректного запуска:
#   ./sum.sh 1.5 -7
if [ "$#" -ne 2 ]; then
  # Сообщение об ошибке отправляем в stderr.
  # >&2 означает "перенаправить stdout этой команды в stderr".
  echo "Error: expected exactly two arguments" >&2

  # Код выхода 1 означает, что программа завершилась с ошибкой.
  exit 1
fi

# Регулярное выражение для проверки числа.
#
# Разбор:
#   ^                       начало строки
#   -?                      необязательный минус
#   ( ... | ... )           один из двух вариантов числа
#   [0-9]+([.][0-9]+)?      целая часть и необязательная дробная часть: 10, 10.5
#   [.][0-9]+               число без целой части: .5
#   $                       конец строки
number_regex='^-?([0-9]+([.][0-9]+)?|[.][0-9]+)$'

# "$1" - первый аргумент скрипта.
# "$2" - второй аргумент скрипта.
#
# [[ ... ]] - расширенная проверка bash.
# =~ проверяет строку на соответствие регулярному выражению.
# ! инвертирует результат проверки.
# || означает логическое "или".
if [[ ! "$1" =~ $number_regex || ! "$2" =~ $number_regex ]]; then
  echo "Error: arguments must be numbers" >&2
  exit 1
fi

# Bash сам по себе плохо подходит для вычислений с дробными числами.
# Например арифметика bash через $(( ... )) работает только с целыми.
# echo "$(($1 + $2))"
# Поэтому используем awk: он умеет складывать и целые, и дробные числа.
#
# -v a="$1" передает первый аргумент в переменную awk `a`.
# -v b="$2" передает второй аргумент в переменную awk `b`.
# BEGIN выполняется один раз сразу при запуске awk.
# print a + b выводит сумму в stdout.
awk -v a="$1" -v b="$2" 'BEGIN { print a + b }'
